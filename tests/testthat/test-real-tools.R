# --- whisper -----------------------------------------------------------------

test_that("whisper really transcribes a prepared wav", {
  skip_on_cran()
  skip_if(!have(check_whisper), "audio.whisper or a local model is missing")
  skip_if(!have(check_ffmpeg), "ffmpeg is needed to generate the input")
  skip_if(!have(check_ffprobe), "ffprobe is needed by aw_check_audio()")

  infile <- real_wav(rate = 16000)
  model <- aw_get_model(Sys.getenv("OPENAC_WHISPER_MODEL"))
  rdsfile <- file.path(withr::local_tempdir(), "out.rds")

  out <- aw_transcribe(infile, model = model, rdsfile = rdsfile)

  expect_true(file.exists(rdsfile))
  # A sine tone yields no meaningful speech, so the transcript's content is not
  # asserted --- only that whisper ran and returned a readable transcription.
  expect_true(is.data.frame(aw_read(out)))
})
