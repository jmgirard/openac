# --- openSMILE ---------------------------------------------------------------

test_that("openSMILE really extracts features that os_read() can read", {
  skip_on_cran()
  skip_if(!have(check_opensmile), "openSMILE is not installed")
  skip_if(!have(check_ffmpeg), "ffmpeg is needed to generate the input")
  skip_if(!have(check_ffprobe), "ffprobe is needed by os_check_audio()")

  config <- "egemaps/v02/eGeMAPSv02"
  skip_if(
    !(config %in% os_list_configs()),
    paste0("this openSMILE install has no ", config)
  )

  infile <- real_wav()
  aggfile <- file.path(withr::local_tempdir(), "agg.csv")

  os_extract(infile, aggfile = aggfile, config = config)

  expect_true(file.exists(aggfile))
  features <- os_read(aggfile)
  # The functionals output is one row; the reader's contract is what is checked.
  expect_identical(nrow(features), 1L)
  expect_true("name" %in% names(features))
  expect_gt(ncol(features), 2)
})

test_that("os_extract_dir really runs openSMILE over a directory", {
  skip_on_cran()
  skip_if(!have(check_opensmile), "openSMILE is not installed")
  skip_if(!have(check_ffmpeg), "ffmpeg is needed to generate the inputs")
  skip_if(!have(check_ffprobe), "ffprobe is needed by os_check_audio()")

  config <- "egemaps/v02/eGeMAPSv02"
  skip_if(
    !(config %in% os_list_configs()),
    paste0("this openSMILE install has no ", config)
  )

  indir <- withr::local_tempdir()
  for (name in c("one.wav", "two.wav")) {
    file.copy(real_wav(), file.path(indir, name))
  }
  aggdir <- file.path(withr::local_tempdir(), "agg")

  result <- os_extract_dir(indir, "wav", aggdir = aggdir, config = config)

  expect_identical(nrow(result), 2L)
  expect_true(all(result$success))
  expect_true(all(file.exists(result$aggfile)))
})

